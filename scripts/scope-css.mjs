#!/usr/bin/env node
/**
 * Turns the stylesheets of one of the original static pages into a stylesheet
 * scoped to that page's wrapper, so it can be imported by a Next.js route
 * without leaking into the rest of the site.
 *
 *   node scripts/scope-css.mjs <slug> <out.css> <page.html | extra.css>...
 *
 * - Collects every <style> of each .html input, and the whole of each .css input, in order.
 * - Prefixes every selector with `.pg-<slug>` (after any leading `html` / `body`, which keeps the
 *   originals' relative specificity); `:root`, `html` and `body` alone become the wrapper itself,
 *   and `body.space X` becomes `body .pg-<slug>.space X`.
 * - Renames @keyframes to `<slug>-<name>` so pages can't override each other's animations.
 * - Points 'Manrope' / 'Hanken Grotesk' at the next/font variables.
 * - Points relative url(...) assets at /site/ (the copies in public/site).
 * - Drops the prototype-only custom cursor and loader, and `cursor: none`.
 * - Starts with a small "revert" layer that undoes the site-wide reset in globals.css
 *   (margins, paddings, image display) for the elements inside the wrapper.
 */
import fs from "node:fs";
import path from "node:path";
import postcss from "postcss";

const [slug, out, ...inputs] = process.argv.slice(2);
if (!slug || !out || inputs.length === 0) {
  console.error("usage: scope-css.mjs <slug> <out.css> <inputs...>");
  process.exit(1);
}
const scope = `.pg-${slug}`;

/** A stylesheet cut off mid-rule (one original ends inside a @keyframes): keep only its complete rules. */
function complete(sheet) {
  let depth = 0;
  let end = 0;
  for (let i = 0; i < sheet.length; i++) {
    if (sheet[i] === "{") depth++;
    else if (sheet[i] === "}" && --depth === 0) end = i + 1;
  }
  return depth === 0 ? sheet : sheet.slice(0, end);
}

let css = "";
for (const file of inputs) {
  const text = fs.readFileSync(file, "utf8");
  if (file.endsWith(".css")) css += `\n${complete(text)}\n`;
  else for (const m of text.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)) css += `\n${complete(m[1])}\n`;
}

// The originals contain a few declarations browsers silently drop (e.g. "{!important;"). Drop them too.
css = css.replace(/([{;])\s*!important\s*;/g, "$1");

const root = postcss.parse(css);

const DROP = /^(#cur|#loader|\.ticker)\b/;
const keyframes = new Map();
root.walkAtRules("keyframes", (at) => {
  const name = at.params.trim();
  const renamed = `${slug}-${name}`;
  keyframes.set(name, renamed);
  at.params = renamed;
});

/**
 * Every selector gains exactly one class (the page wrapper), so the originals'
 * relative specificity is unchanged. `html` / `body` stay where they were (the
 * wrapper is inside them); classes on body (body.space) move to the wrapper.
 */
function scopeSelector(sel) {
  let s = sel.trim();
  if (DROP.test(s)) return null;
  if (s === ":root" || s === "html" || s === "body" || s === "html body") return scope;
  s = s.replace(/^:root\s*/, "");
  const m = s.match(/^((?:html\s+)?body)((?:\.[\w-]+)*)(?=[\s>+~:]|$)/) || s.match(/^(html)()(?=[\s>+~]|$)/);
  if (m) {
    const rest = s.slice(m[0].length);
    if (!rest.trim()) return `${m[1]} ${scope}${m[2]}`;
    return `${m[1]} ${scope}${m[2]}${/^\s/.test(rest) ? rest : ` ${rest.replace(/^[>+~]\s*/, "")}`}`;
  }
  return `${scope} ${s}`;
}

root.walkRules((rule) => {
  if (rule.parent?.type === "atrule" && /keyframes$/.test(rule.parent.name)) return;
  const scoped = rule.selectors.map(scopeSelector).filter(Boolean);
  if (scoped.length === 0) rule.remove();
  else rule.selectors = scoped;
});

const FONT = (v) =>
  v
    .replace(/(['"])Manrope\1/g, "var(--font-manrope)")
    .replace(/(['"])Hanken Grotesk\1/g, "var(--font-hanken-grotesk)");

root.walkDecls((decl) => {
  if (decl.prop === "cursor" && /none/.test(decl.value)) {
    decl.remove();
    return;
  }
  if (decl.prop === "font-family" || decl.prop === "font" || decl.prop.startsWith("--")) decl.value = FONT(decl.value);
  // Relative asset URLs point at the copies in /public/site.
  if (decl.value.includes("url(")) {
    decl.value = decl.value.replace(/url\((['"]?)(?!data:|https?:|\/|#)([^'")]+)\1\)/g, (_, q, u) => `url(${q}/site/${u}${q})`);
  }
  if (decl.prop === "animation" || decl.prop === "animation-name") {
    decl.value = decl.value.replace(/[A-Za-z_][\w-]*/g, (w) => keyframes.get(w) ?? w);
  }
});

// Remove empty at-rules left behind.
root.walkAtRules((at) => {
  if (at.nodes && at.nodes.length === 0) at.remove();
});

const revert = `/* Generated by scripts/scope-css.mjs from the original page. Do not edit by hand; re-run the script. */
${scope} :where(*){margin:revert;padding:revert}
${scope} :where(img){display:revert}
${scope} :where(button){font:revert;color:revert;background:revert;border:revert;cursor:revert}
${scope}{display:block}
`;

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, revert + root.toString().replace(/\n{3,}/g, "\n\n"));
console.log(`${out}: ${fs.statSync(out).size} bytes, ${keyframes.size} keyframes`);
